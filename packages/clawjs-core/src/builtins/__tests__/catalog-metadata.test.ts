const EVIDENCE_TAGS = new Set([
  "human_recognizable",
  "market_validated",
  "multi_domain_reuse",
  "agent_useful",
]);

const RELATION_KINDS = new Set([
  "ownership",
  "membership",
  "participant",
  "line_item",
  "source_import",
  "attachment",
  "location",
  "temporal_event",
  "financial_transaction",
  "observation_sample",
  "dependency",
  "generic",
]);

const REQUIRED_REASONS = new Set([
  "identity",
  "integrity",
  "lifecycle",
  "relation_integrity",
]);

test("catalog metadata baseline tracks existing built-in collections", () => {
  assert.equal(LEGACY_METADATA_BASELINE.size, 509);
  const currentNames = new Set(BUILTIN_COLLECTIONS.map((collection) => collection.name));
  for (const name of LEGACY_METADATA_BASELINE) {
    assert.ok(currentNames.has(name), `Legacy catalog baseline includes missing collection "${name}"`);
  }
});
test("new built-in collections declare purpose and evidence", () => {
  for (const collection of BUILTIN_COLLECTIONS) {
    if (LEGACY_METADATA_BASELINE.has(collection.name)) continue;

    assert.ok(collection.catalog, `New collection "${collection.name}" must declare catalog metadata`);
    assert.ok(collection.catalog.purpose.trim().length > 0, `${collection.name} catalog purpose is empty`);
    assert.ok(collection.catalog.evidence.length > 0, `${collection.name} catalog evidence is empty`);

    for (const tag of collection.catalog.evidence) {
      assert.ok(EVIDENCE_TAGS.has(tag), `${collection.name} uses unknown evidence tag "${tag}"`);
    }

    for (const field of collection.fields) {
      if (field.required) {
        assert.ok(
          field.requiredReason && REQUIRED_REASONS.has(field.requiredReason),
          `${collection.name}.${field.name} is required without a requiredReason`,
        );
      }
      if (field.type === "relation") {
        assert.ok(
          field.relation?.kind && RELATION_KINDS.has(field.relation.kind),
          `${collection.name}.${field.name} is a relation without semantic kind`,
        );
      }
    }
  }
});

test("catalog metadata is valid when present on any collection", () => {
  for (const collection of BUILTIN_COLLECTIONS) {
    if (collection.catalog) {
      assert.ok(collection.catalog.purpose.trim().length > 0, `${collection.name} catalog purpose is empty`);
      assert.ok(collection.catalog.evidence.length > 0, `${collection.name} catalog evidence is empty`);
      for (const tag of collection.catalog.evidence) {
        assert.ok(EVIDENCE_TAGS.has(tag), `${collection.name} uses unknown evidence tag "${tag}"`);
      }
    }

    for (const field of collection.fields) {
      for (const alias of field.aliases ?? []) {
        assert.equal(alias, alias.trim(), `${collection.name}.${field.name} alias has surrounding whitespace`);
        assert.ok(alias.length > 0, `${collection.name}.${field.name} has empty alias`);
      }

      if (field.requiredReason) {
        assert.ok(
          REQUIRED_REASONS.has(field.requiredReason),
          `${collection.name}.${field.name} uses unknown requiredReason "${field.requiredReason}"`,
        );
      }

      if (field.relation?.kind) {
        assert.ok(
          RELATION_KINDS.has(field.relation.kind),
          `${collection.name}.${field.name} uses unknown relation kind "${field.relation.kind}"`,
        );
      }
    }
  }
});
